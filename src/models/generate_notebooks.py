# 2. Notebook 02: Modeling
modeling_cells = [
    md_cell("""# AgroShield AI — Machine Learning Model Training
### Multi-Class Grain Spoilage Classifier (Ensemble Architecture)
**Author:** Enzo Oliveira dos Santos  
**Algorithms:** Scikit-Learn RandomForestClassifier, 5-Fold Stratified Cross-Validation

This notebook demonstrates the predictive modeling pipeline for early detection of biological heating and roof condensation in Iowa silos."""),
    code_cell("""import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split, cross_val_score
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score
import joblib

df = pd.read_csv('../data/samples/iowa_silo_telemetry_sample.csv')

features = ['crop_code', 'grain_temp_c', 'grain_moisture_pct', 'ambient_temp_c', 'ambient_rh_pct', 'days_in_storage', 'emc_pct', 'temp_gradient_c']
X = df[features]
y = df['risk_level']

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.20, random_state=42, stratify=y)
print(f"Training set: {X_train.shape[0]} samples | Test set: {X_test.shape[0]} samples")"""),
    code_cell("""# Model Training
clf = RandomForestClassifier(n_estimators=150, max_depth=12, min_samples_split=4, random_state=42, n_jobs=-1)
clf.fit(X_train, y_train)

y_pred = clf.predict(X_test)
print(f"Test Accuracy: {accuracy_score(y_test, y_pred) * 100:.2f}%")
print("\\nClassification Report:")
print(classification_report(y_test, y_pred, target_names=['SAFE', 'WARNING_AERATE', 'CRITICAL_MOLD']))"""),
    code_cell("""# Feature Importance Ranking
importances = pd.Series(clf.feature_importances_, index=features).sort_values(ascending=False)
plt.figure(figsize=(10, 5))
importances.plot(kind='bar', color='#2b8a3e')
plt.title('Feature Importance — Predictors of Silo Spoilage Risk')
plt.ylabel('Relative Importance Score')
plt.xticks(rotation=45)
plt.grid(axis='y', alpha=0.3)
plt.show()""")
]

